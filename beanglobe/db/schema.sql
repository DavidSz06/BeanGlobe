CREATE OR REPLACE FUNCTION public.validate_booking_status_transition()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        IF NEW.status <> 'pending' THEN
            RAISE EXCEPTION 'Invalid initial booking status: %', NEW.status
                USING ERRCODE = 'check_violation';
        END IF;

        RETURN NEW;
    END IF;

    IF OLD.status = 'pending'
       AND NEW.status NOT IN ('pending', 'confirmed', 'cancelled') THEN
        RAISE EXCEPTION
            'Invalid booking status transition: pending -> %',
            NEW.status
            USING ERRCODE = 'check_violation';
    END IF;

    IF OLD.status = 'confirmed'
       AND NEW.status NOT IN ('confirmed', 'completed', 'cancelled') THEN
        RAISE EXCEPTION
            'Invalid booking status transition: confirmed -> %',
            NEW.status
            USING ERRCODE = 'check_violation';
    END IF;

    IF OLD.status IN ('completed', 'cancelled')
       AND NEW.status <> OLD.status THEN
        RAISE EXCEPTION
            'Invalid booking status transition: % -> %',
            OLD.status,
            NEW.status
            USING ERRCODE = 'check_violation';
    END IF;

    RETURN NEW;
END;
$$;


CREATE TRIGGER validate_booking_status_insert
    BEFORE INSERT ON public.bookings
    FOR EACH ROW
    EXECUTE FUNCTION public.validate_booking_status_transition();


CREATE TRIGGER validate_booking_status_update
    BEFORE UPDATE OF status ON public.bookings
    FOR EACH ROW
    WHEN (OLD.status IS DISTINCT FROM NEW.status)
    EXECUTE FUNCTION public.validate_booking_status_transition();


